typedef uint32_t ACCESS_MASK;

struct ACE
{
	ACCESS_MASK Mask;
	BYTE AceType;
	BYTE AceFlags;
	SID Sid;
};

constexpr BYTE ACCESS_ALLOWED_ACE_TYPE	= 0;
constexpr BYTE ACCESS_DENIED_ACE_TYPE	= 1;

#define ACL_REVISION (1)

struct ACL
{
	BYTE AclRevision;
	WORD AclSize;
	WORD AclCount;
	alignas(ACE) char AceBuffer[];
};

typedef WORD SECURITY_DESCRIPTOR_CONTROL;
typedef SID* PSID;
typedef ACL* PACL;

